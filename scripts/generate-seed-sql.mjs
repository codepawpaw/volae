// Builds supabase/seed.sql from the JSON files in seed/. Run with `npm run db:seed-sql`.
// Every insert uses ON CONFLICT DO NOTHING, so the seed is safe to run more than once.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.join(path.dirname(new URL(import.meta.url).pathname), "..");
const read = (name) => JSON.parse(readFileSync(path.join(root, "seed", `${name}.json`), "utf8"));

// Embed the JSON as a dollar-quoted literal and let Postgres unpack it.
const json = (value) => `$json$${JSON.stringify(value)}$json$::jsonb`;

const brands = read("brands");
const categories = read("categories");
const products = read("products");
const subscribers = read("subscribers");
const orders = read("orders");
const settings = read("settings");

// Parents before children so the self-referencing foreign key is satisfied.
categories.sort((a, b) => (a.parentId === null ? 0 : 1) - (b.parentId === null ? 0 : 1));

const orderItems = orders.flatMap((o) => o.lines.map((l, position) => ({ ...l, orderId: o.id, position })));

const sql = `-- Generated by scripts/generate-seed-sql.mjs from seed/*.json. Do not edit by hand.

insert into public.brands (id, name, slug, description, logo, image, sort_order, created_at)
select id, name, slug, description, logo, image, "order", "createdAt"
from jsonb_to_recordset(${json(brands)})
  as x(id text, name text, slug text, description text, logo text, image text, "order" int, "createdAt" timestamptz)
on conflict do nothing;

insert into public.categories (id, name, slug, parent_id, description, image, sort_order, created_at)
select id, name, slug, "parentId", description, image, "order", "createdAt"
from jsonb_to_recordset(${json(categories)})
  as x(id text, name text, slug text, "parentId" text, description text, image text, "order" int, "createdAt" timestamptz)
on conflict do nothing;

insert into public.products (id, name, slug, brand_id, category_id, price, sale_price, description, features, colors,
  sizes, activities, images, badge, is_new, is_active, created_at, updated_at)
select id, name, slug, "brandId", "categoryId", price, "salePrice", description,
  array(select jsonb_array_elements_text(features)), colors,
  array(select jsonb_array_elements_text(sizes)),
  array(select jsonb_array_elements_text(activities)),
  array(select jsonb_array_elements_text(images)),
  badge, "isNew", "isActive", "createdAt", "updatedAt"
from jsonb_to_recordset(${json(products)})
  as x(id text, name text, slug text, "brandId" text, "categoryId" text, price bigint, "salePrice" bigint,
    description text, features jsonb, colors jsonb, sizes jsonb, activities jsonb, images jsonb, badge text,
    "isNew" boolean, "isActive" boolean, "createdAt" timestamptz, "updatedAt" timestamptz)
on conflict do nothing;

insert into public.subscribers (email, created_at)
select email, "createdAt"
from jsonb_to_recordset(${json(subscribers)}) as x(email text, "createdAt" timestamptz)
on conflict do nothing;

insert into public.orders (id, number, customer_name, customer_phone, customer_address, customer_note, subtotal, total,
  status, created_at, updated_at)
select id, number, customer->>'name', customer->>'phone', customer->>'address', coalesce(customer->>'note', ''),
  total, total, status::public.order_status, "createdAt", "updatedAt"
from jsonb_to_recordset(${json(orders)})
  as x(id text, number text, customer jsonb, total bigint, status text, "createdAt" timestamptz, "updatedAt" timestamptz)
on conflict do nothing;

insert into public.order_items (order_id, position, product_id, name, brand, color, size, qty, unit_price)
select "orderId", position, (select p.id from public.products p where p.id = x."productId"), name, brand, color, size,
  qty, "unitPrice"
from jsonb_to_recordset(${json(orderItems)})
  as x("orderId" text, position int, "productId" text, name text, brand text, color text, size text, qty int,
    "unitPrice" bigint)
on conflict do nothing;

insert into public.settings (key, value)
select key, value from jsonb_each(${json(settings)})
on conflict do nothing;
`;

writeFileSync(path.join(root, "supabase", "seed.sql"), sql);
console.log(
  `Wrote supabase/seed.sql: ${brands.length} brands, ${categories.length} categories, ${products.length} products, ` +
    `${subscribers.length} subscribers, ${orders.length} orders, ${Object.keys(settings).length} settings.`,
);
